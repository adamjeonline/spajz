# (Špajz) the Czech interface: scripts/i18n/cs/*.txt (same format as tr/*.txt) -> renderer/i18n-cs-data.js, shared/i18n-cs.json
# Usage (in the project folder):  python3 scripts/i18n/build_cs.py
import os, runpy, sys
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(os.path.dirname(here)); os.chdir(here)
os.environ['I18N_DIR'] = 'cs'; os.environ['I18N_OUT'] = 'cs.json'
runpy.run_path(os.path.join(here, 'compile.py'))
d = open(os.path.join(here, 'cs.json'), encoding='utf-8').read()
js = '// Generated by scripts/i18n/build_cs.py from scripts/i18n/cs. Do not edit by hand.\nwindow.__BS_CS=' + d + ';\n'
for p in ['renderer/i18n-cs-data.js', 'renderer/companion/i18n-cs-data.js']:
    if os.path.isdir(os.path.dirname(os.path.join(root, p))): open(os.path.join(root, p), 'w', encoding='utf-8').write(js)
open(os.path.join(root, 'shared/i18n-cs.json'), 'w', encoding='utf-8').write(d)
os.remove(os.path.join(here, 'cs.json')); print('ok')
